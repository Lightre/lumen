"""Collect a reviewable Windows dependency notice snapshot from Cargo.lock."""

import hashlib
import json
from pathlib import Path
import re
import subprocess
import tarfile
from urllib.request import urlopen
from urllib.error import HTTPError

ROOT = Path(__file__).resolve().parent.parent
TARGET = "x86_64-pc-windows-msvc"
UPSTREAM_FILES = {
    "emilk/egui": ["LICENSE-APACHE", "LICENSE-MIT"],
    "AccessKit/accesskit": ["LICENSE-APACHE", "LICENSE-MIT", "LICENSE.chromium"],
    "brendanzab/gl-rs": ["LICENSE"],
    "aclysma/profiling": ["LICENSE-APACHE", "LICENSE-MIT"],
}


def upstream_licenses(package, directory):
    repository = package.get("repository") or ""
    match = re.match(r"https://github.com/([^/]+/[^/]+)", repository)
    slug = match.group(1).removesuffix(".git") if match else ""
    if slug not in UPSTREAM_FILES:
        raise RuntimeError(f"Review missing license files: {package['name']}")
    revision = json.loads((directory / ".cargo_vcs_info.json").read_text())["git"]["sha1"]
    for name in UPSTREAM_FILES[slug]:
        url = f"https://raw.githubusercontent.com/{slug}/{revision}/{name}"
        cache = ROOT / "target/license-cache" / slug / revision / name
        if not cache.exists():
            try:
                with urlopen(url, timeout=30) as response:
                    content = response.read().decode("utf-8")
            except HTTPError as error:
                if error.code != 404 or slug != "emilk/egui":
                    raise RuntimeError(f"Could not retrieve {url}") from error
                # Some published egui crates reference a revision unavailable upstream.
                # Use the published version tag, never a moving branch.
                url = f"https://raw.githubusercontent.com/{slug}/{package['version']}/{name}"
                with urlopen(url, timeout=30) as response:
                    content = response.read().decode("utf-8")
            if len(content) < 100:
                raise RuntimeError(f"Unexpected license response: {url}")
            cache.parent.mkdir(parents=True, exist_ok=True)
            cache.write_text(content, encoding="utf-8", newline="\n")
            cache.with_suffix(cache.suffix + ".url").write_text(url, encoding="utf-8")
        url_file = cache.with_suffix(cache.suffix + ".url")
        if url_file.exists():
            url = url_file.read_text(encoding="utf-8")
        yield url, cache.read_text(encoding="utf-8")


def package_notices(package):
    directory = Path(package["manifest_path"]).parent
    files = sorted(
        path for path in directory.rglob("*")
        if path.is_file() and (
            path.name.lower().startswith(("license", "licence", "copying", "notice"))
            or path.name.lower() in ("copyright", "copyright.txt")
            or (path.parent.name == "fonts" and path.suffix == ".txt")
        )
    )
    if files:
        for path in files:
            yield path.relative_to(directory).as_posix(), path.read_text(encoding="utf-8-sig")
    else:
        yield from upstream_licenses(package, directory)
    if package["name"] == "epaint_default_fonts" and files:
        # The font notices do not replace the crate's own workspace license.
        yield from upstream_licenses(package, directory)
    if package["name"] == "khronos_api":
        for path in sorted((directory / "api/xml").glob("*.xml")):
            with path.open(encoding="utf-8") as source:
                header = source.read(65536)
            comment = re.search(r"<comment>(.*?)</comment>", header, re.DOTALL)
            if comment:
                yield path.relative_to(directory).as_posix() + " header", comment.group(1)


def main():
    metadata = json.loads(subprocess.check_output([
        "cargo", "metadata", "--locked", "--format-version", "1",
        "--filter-platform", TARGET,
    ], cwd=ROOT, encoding="utf-8"))
    packages = sorted(
        (p for p in metadata["packages"] if p["id"] not in metadata["workspace_members"]),
        key=lambda p: (p["name"], p["version"]),
    )
    lock_hash = hashlib.sha256((ROOT / "Cargo.lock").read_text(encoding="utf-8").encode("utf-8")).hexdigest()
    parts = [
        "Lumen — third-party notices",
        f"Target: {TARGET}",
        f"Cargo.lock SHA-256: {lock_hash}",
        "Lockfile hash uses UTF-8 with LF line endings.",
        "",
        "Generated by scripts/update-third-party-notices.py; review before distribution.",
        "Includes the locked Windows runtime, build, and development dependency graph.",
        "Not every listed component is included in the distributed executable.",
        "Components and bundled fonts retain their original licenses and copyrights.",
        "Where a dependency offers alternative licenses, its original expression is shown.",
        "",
        "DEPENDENCIES",
        "",
    ]
    texts = {}
    for package in packages:
        label = f"{package['name']} {package['version']}"
        if not package.get("license"):
            raise RuntimeError(f"Review missing license metadata: {label}")
        parts.append(f"{label} — {package['license']}")
        parts.append(f"  {package.get('repository') or 'https://crates.io/crates/' + package['name']}")
        notices = list(package_notices(package))
        if not notices:
            raise RuntimeError(f"No notices collected: {label}")
        for source, content in notices:
            content = content.replace("\r\n", "\n").strip()
            if not content:
                raise RuntimeError(f"Empty notice: {label} / {source}")
            texts.setdefault(content, []).append(f"{label} / {source}")
    native_sources = ROOT / "native/sources"
    for package in json.loads((native_sources / "manifest.json").read_text(encoding="utf-8")):
        archive = native_sources / package["archive"]
        if hashlib.sha256(archive.read_bytes()).hexdigest() != package["sha256"]:
            raise RuntimeError(f"Native source hash mismatch: {archive.name}")
        label = f"{package['name']} {package['version']}"
        parts += [f"{label} — {package['license']}",
                  f"  {package['repository']}/tree/{package['revision']}",
                  f"  Source archive SHA-256: {package['sha256']}"]
        with tarfile.open(archive) as source:
            for member in source.getmembers():
                if member.isfile() and Path(member.name).name.lower().startswith(("copying", "license", "notice")):
                    content = source.extractfile(member).read().decode("utf-8-sig").replace("\r\n", "\n").strip()
                    if content:
                        texts.setdefault(content, []).append(f"{label} / {member.name}")
    parts += ["", "LICENSE TEXTS AND NOTICES", ""]
    for content, sources in texts.items():
        parts += ["=" * 78, *sources, "=" * 78, "", content, ""]
    output = ROOT / "THIRD_PARTY_NOTICES.txt"
    output.write_text("\n".join(parts), encoding="utf-8", newline="\n")
    print(f"Wrote {len(packages)} dependency entries and {len(texts)} distinct notices.")


if __name__ == "__main__":
    main()
